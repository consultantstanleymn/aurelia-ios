#!/usr/bin/env bash
# Bakes the provider key into the app at build time.
#
# Why this exists and why it is not just a line in the source: the key is a real credential that
# can spend money, and the key is readable out of a built .ipa with `strings` the same as it is
# out of a .swift file. Putting it in a source file would additionally put it in git history,
# which cannot be taken back once the repo is published.
#
# So the key is read from the file the Python tutor already keeps, written into a generated Swift
# file that .gitignore excludes, and compiled in. The app then needs nothing pasted into it, and
# `git` never sees the key at all.
#
#   bash tools/inject-key.sh                 # from ~/.config/study-mentor/deepseek.key
#   bash tools/inject-key.sh /path/to/key    # from somewhere else
#   bash tools/inject-key.sh --clear         # remove it
#
# Rotate the key before sharing any .ipa. The binary cannot be un-baked.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TARGET="$ROOT/Sources/StudyBuddy/GeneratedAPIKey.swift"

if [ "${1:-}" = "--clear" ]; then
  rm -f "$TARGET"
  echo "cleared $TARGET"
  exit 0
fi

KEY_FILE="${1:-$HOME/.config/study-mentor/deepseek.key}"
if [ ! -f "$KEY_FILE" ]; then
  echo "no key file at $KEY_FILE" >&2
  exit 1
fi

KEY="$(tr -d '[:space:]' < "$KEY_FILE")"
if [ -z "$KEY" ]; then
  echo "key file is empty" >&2
  exit 1
fi

# Written with a restricted umask because for a moment this file holds the secret itself.
( umask 077
cat > "$TARGET" <<SWIFT
// GENERATED by tools/inject-key.sh — do not commit, do not edit, do not copy anywhere.
//
// This file exists only on this machine and only for this build. It is listed in .gitignore so
// the key cannot reach the repository. Regenerate it with the same command, or remove it with
// --clear; the app falls back to the Keychain and then to a prompt when it is absent.

enum InjectedAPIKey {
    /// Empty when tools/inject-key.sh has not been run.
    static let value = "__AURELIA_KEY__"
}
SWIFT
 )
sed -i "s|__AURELIA_KEY__|$KEY|" "$TARGET"

printf '  injected %s chars from %s\n' "${#KEY}" "$KEY_FILE"
